# ── Surface features (PDDL-structural only, NO semantic overlap) ──────────────

def compute_surface_features(records):
    """
    30-dim PDDL structural features.
    These are purely syntactic/structural counts — they cannot encode
    semantic domain knowledge (precondition structure, causal chains).
    That is the exclusive domain of the FM embedding.
    """
    N     = len(records)
    feats = np.zeros((N, 30), dtype=np.float32)

    for i, r in enumerate(records):
        desc    = r["description"]
        words   = desc.lower().split()
        problem = r.get("problem_pddl", "")
        init_f  = r.get("init_facts", [])
        goal_f  = r.get("goal_facts",  [])

        # 0: n_objects
        feats[i, 0] = float(r.get("n_objects", 0))
        # 1: n_init_facts
        feats[i, 1] = float(len(init_f))
        # 2: n_goal_facts
        feats[i, 2] = float(len(goal_f))
        # 3: ratio goal/init
        feats[i, 3] = float(len(goal_f)) / max(float(len(init_f)), 1)
        # 4: n_objects / n_goals
        feats[i, 4] = float(r.get("n_objects", 1)) / max(len(goal_f), 1)

        # 5–7: PDDL description text stats
        feats[i, 5] = float(len(words))
        sents = [s.strip() for s in re.split(r'[.!?]', desc) if s.strip()]
        feats[i, 6] = float(len(sents))
        feats[i, 7] = float(len(set(words))) / max(len(words), 1)

        # 8–9: Number of distinct predicate types in init/goal
        def count_preds(facts):
            preds = set()
            for f in facts:
                m = re.match(r'\((\S+)', f)
                if m: preds.add(m.group(1))
            return len(preds)
        feats[i,  8] = float(count_preds(init_f))
        feats[i,  9] = float(count_preds(goal_f))

        # 10–11: Arity of goal predicates (average, max)
        arities = []
        for f in goal_f:
            args = re.findall(r'\??\w+', f.strip("()"))
            arities.append(max(0, len(args) - 1))
        feats[i, 10] = float(np.mean(arities)) if arities else 0
        feats[i, 11] = float(max(arities)) if arities else 0

        # 12: Number of distinct object types (from "- type" patterns)
        types = re.findall(r'- (\w+)', problem)
        feats[i, 12] = float(len(set(types)))

        # 13: Number of actions in domain (count :action)
        feats[i, 13] = float(r.get("domain_pddl", "").count(":action"))

        # 14: Domain name hash (structural proxy for domain identity)
        domain_hash = {"blocksworld": 0, "mystery_blocksworld": 1,
                       "gripper": 2, "ferry": 3, "logistics": 4,
                       "satellite": 5, "rovers": 6, "depot": 7}
        feats[i, 14] = float(domain_hash.get(r.get("domain", ""), -1))

        # 15–19: Text readability proxies
        sl = [len(s.split()) for s in sents] or [0]
        feats[i, 15] = float(np.mean(sl))
        feats[i, 16] = float(np.max(sl))
        asl = np.mean(sl) if sl else 10
        asy = np.mean([max(1, len(re.findall(r'[aeiou]', w))) for w in words]) if words else 2
        feats[i, 17] = 0.39 * asl + 11.8 * asy - 15.59   # Flesch-Kincaid grade
        feats[i, 18] = 206.835 - 1.015 * asl - 84.6 * asy # Flesch reading ease

        # 19: Fraction of numeric tokens in description
        feats[i, 19] = float(len(re.findall(r'\b\d+\b', desc))) / max(len(words), 1)

        # 20–24: Structural PDDL complexity
        # Objects mentioned in goal that also appear in init
        obj_in_both = len(set(init_f) & set(goal_f))
        feats[i, 20] = float(obj_in_both)
        # PDDL problem string length (proxy for encoding length)
        feats[i, 21] = float(len(problem)) / 500.0
        # Negation count in problem (:not)
        feats[i, 22] = float(problem.count("not"))
        # Number of quantifier patterns
        feats[i, 23] = float(problem.count("forall") + problem.count("exists"))
        # Estimated search depth proxy: n_goals * n_objects
        feats[i, 24] = float(len(goal_f) * r.get("n_objects", 1)) / 10.0

        # 25–29: Description semantic-agnostic word stats
        seq_words = ["then", "next", "first", "finally", "after", "before",
                     "until", "once", "while", "move", "load", "stack"]
        feats[i, 25] = float(sum(1 for w in words if w in seq_words))
        feats[i, 26] = float(desc.count(","))
        feats[i, 27] = float(len(re.findall(r'\b\d+\b', desc)))
        feats[i, 28] = float(len(words) > 50)   # is_long_description
        feats[i, 29] = float(len(goal_f) > 2)   # is_multi_goal

    feats = np.nan_to_num(feats, nan=0.0, posinf=5.0, neginf=0.0)
    return feats


# ── FM embeddings (LLaMA-3 or sentence-transformer fallback) ──────────────────

def compute_fm_embeddings(records, model_name="all-mpnet-base-v2", use_llm=False):
    """
    Embed each PDDL problem description using:
      - LLaMA-3-8B last hidden state (preferred, requires ~16GB VRAM)
      - all-mpnet-base-v2 sentence transformer (fallback, ~2GB RAM)

    The embedding captures semantic domain knowledge:
      - Causal structure of preconditions/effects
      - Multi-step dependency patterns
      - Domain-specific reasoning patterns
    This is what surface features CANNOT capture.
    """
    descriptions = [
        f"Domain: {r['domain']}. Problem: {r['description']} "
        f"Initial state has {len(r['init_facts'])} facts. "
        f"Goal requires {len(r['goal_facts'])} conditions."
        for r in records
    ]

    if use_llm:
        try:
            import torch
            from transformers import AutoTokenizer, AutoModel
            print("    Loading LLaMA-3-8B for embeddings...")
            model_id = "meta-llama/Meta-Llama-3-8B"
            tokenizer = AutoTokenizer.from_pretrained(model_id)
            llm = AutoModel.from_pretrained(model_id, torch_dtype=torch.float16,
                                             device_map="auto")
            llm.eval()
            embeddings = []
            batch_size = 8
            with torch.no_grad():
                for i in range(0, len(descriptions), batch_size):
                    batch = descriptions[i:i + batch_size]
                    enc   = tokenizer(batch, return_tensors="pt",
                                      padding=True, truncation=True,
                                      max_length=512).to(llm.device)
                    out   = llm(**enc, output_hidden_states=True)
                    # Mean-pool last hidden state
                    hidden = out.hidden_states[-1]
                    mask   = enc["attention_mask"].unsqueeze(-1).float()
                    pooled = (hidden * mask).sum(1) / mask.sum(1)
                    embeddings.append(pooled.cpu().float().numpy())
            X_fm = np.vstack(embeddings)
            # L2-normalise
            norms = np.linalg.norm(X_fm, axis=1, keepdims=True)
            X_fm /= np.maximum(norms, 1e-10)
            print(f"    LLaMA-3 embeddings: shape={X_fm.shape}")
            return X_fm.astype(np.float32)
        except Exception as e:
            print(f"    LLaMA-3 failed ({e}), falling back to sentence-transformer")

    # Sentence-transformer fallback
    try:
        from sentence_transformers import SentenceTransformer
        print(f"    Loading {model_name}...")
        st_model = SentenceTransformer(model_name)
        print(f"    Encoding {len(descriptions)} problem descriptions...")
        emb = st_model.encode(descriptions, batch_size=32,
                               show_progress_bar=True,
                               normalize_embeddings=True)
        print(f"    Sentence-transformer embeddings: shape={emb.shape}")
        return emb.astype(np.float32)
    except Exception as e:
        print(f"    sentence-transformers failed ({e}), using random fallback")
        rng2  = np.random.default_rng(0)
        X_fm  = rng2.normal(0, 1, (len(records), 768)).astype(np.float32)
        X_fm /= np.linalg.norm(X_fm, axis=1, keepdims=True)
        return X_fm


# ── Dataset generation ────────────────────────────────────────────────────────

def generate_dataset(domains, n_per_level, rng):
    """
    Generate planning instances for each domain × complexity level.

    Labels:
      n_steps : plan length from BFS solver (primary label for regression)
      success : 1 if n_steps <= per-domain median, else 0
                Natural difficulty binary split — NO synthetic failure injection.
                Avoids the trivial-separability problem of corrupted goals.

    Success rate will be ~50% per domain by construction.
    """
    import numpy as _np
    records     = []
    instance_id = 0

    for domain in domains:
        gen = GENERATORS.get(domain)
        if gen is None:
            print(f"  No generator for {domain}, skipping")
            continue

        n_levels = COMPLEXITY_N.get(domain, [3, 4, 5, 6, 7])
        for level, n_obj in enumerate(n_levels):
            level_records = []
            attempts = 0
            while len(level_records) < n_per_level and attempts < n_per_level * 6:
                attempts += 1
                try:
                    ep = gen(n_obj, rng)
                except Exception:
                    continue
                ep["instance_id"] = instance_id
                ep["complexity"]  = level
                ep["task_type"]   = domain
                ep["valid"]       = True   # BFS-solved or heuristic estimate
                instance_id      += 1
                level_records.append(ep)
            records.extend(level_records)

    # Natural binary label: easy (1) vs hard (0) split by per-domain n_steps median
    for domain in set(r["task_type"] for r in records):
        domain_recs = [r for r in records if r["task_type"] == domain]
        steps       = [r.get("n_steps", 0) for r in domain_recs]
        med         = float(_np.median(steps))
        for r in domain_recs:
            r["success"] = int(r.get("n_steps", 0) <= med)

    return records


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n_per_level",  type=int, default=40,
                        help="Instances per domain×complexity level")
    parser.add_argument("--quick",    action="store_true",
                        help="Quick: 5 domains, 15 instances/level")
    parser.add_argument("--skip_fm",  action="store_true",
                        help="Skip FM embedding (use random vectors)")
    parser.add_argument("--use_llm",  action="store_true",
                        help="Use LLaMA-3 embeddings instead of sentence-transformer")
    parser.add_argument("--fm_model", default="all-mpnet-base-v2",
                        help="Sentence-transformer model name")
    parser.add_argument("--force",    action="store_true",
                        help="Force regeneration of all data")
    args = parser.parse_args()

    if args.quick:
        domains      = QUICK_DOMAINS
        n_per_level  = 15
        print(f"Quick mode: {len(domains)} domains × 5 levels × {n_per_level} = "
              f"{len(domains)*5*n_per_level} instances")
    else:
        domains      = ALL_DOMAINS
        n_per_level  = args.n_per_level
        print(f"Full mode: {len(domains)} domains × 5 levels × {n_per_level} = "
              f"{len(domains)*5*n_per_level} instances")

    rng = np.random.default_rng(SEED)

    # ── Generate episodes ──────────────────────────────────────────────────
    ep_path      = DATA_DIR / "episodes.json"
    manifest_path = DATA_DIR / "data_manifest.json"

    def _read_manifest():
        try:
            return json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
        except Exception:
            return {}

    def _write_manifest(domains_used, n_instances, n_per_level_used, fm_type):
        manifest_path.write_text(json.dumps({
            "domains":     sorted(domains_used),
            "n_instances": n_instances,
            "n_per_level": n_per_level_used,
            "fm_type":     fm_type,   # "random" or model name
        }, indent=2))

    manifest = _read_manifest()
    want_fm_type = "random" if args.skip_fm else args.fm_model

    reasons = []
    if not ep_path.exists():
        reasons.append("no episodes file")
    elif args.force:
        reasons.append("--force flag")
    elif "complexity" not in (json.loads(ep_path.read_text()) or [{}])[0]:
        reasons.append("stale ScienceWorld cache")
    elif set(manifest.get("domains", [])) != set(domains):
        reasons.append(f"domain mismatch: cached={sorted(manifest.get('domains',[]))}"
                       f" vs requested={sorted(domains)}")
    elif manifest.get("n_per_level", 0) < n_per_level:
        reasons.append(f"too few instances/level: cached={manifest.get('n_per_level',0)}"
                       f" vs requested={n_per_level}")

    need_regen = len(reasons) > 0
    if need_regen:
        print(f"  Regenerating episodes: {'; '.join(reasons)}")

    fm_need_regen = need_regen or (manifest.get("fm_type") != want_fm_type)
    if fm_need_regen and not need_regen:
        print(f"  FM type changed: cached={manifest.get('fm_type','?')} "
              f"vs requested={want_fm_type}. Will recompute FM.")
    if not need_regen:
        print(f"Loading existing episodes from {ep_path}")
        records = json.loads(ep_path.read_text())
        records = [r for r in records if r.get("task_type") in set(domains)]
        if not records:
            print("  No matching records after domain filter — regenerating")
            need_regen = True
            fm_need_regen = True
    if need_regen:
        print("Generating PDDL planning episodes...")
        records = generate_dataset(domains, n_per_level, rng)

        def _to_python(obj):
            """Recursively convert numpy scalars/arrays to native Python types."""
            if isinstance(obj, dict):
                return {k: _to_python(v) for k, v in obj.items()
                        if k != "domain_pddl"}
            if isinstance(obj, list):
                return [_to_python(v) for v in obj]
            if isinstance(obj, np.integer):
                return int(obj)
            if isinstance(obj, np.floating):
                return float(obj)
            if isinstance(obj, np.bool_):
                return bool(obj)
            if isinstance(obj, np.ndarray):
                return obj.tolist()
            return obj

        save_records = [_to_python(r) for r in records]
        ep_path.write_text(json.dumps(save_records, indent=2))
        print(f"Generated {len(records)} episodes to {ep_path}")

    print(f"\nDataset summary:")
    print(f"  Total:         {len(records)}")
    print(f"  Success rate:  {np.mean([r['success'] for r in records]):.3f}")
    print(f"  Domains:       {len(set(r['task_type'] for r in records))}")

    domain_counts = defaultdict(int)
    for r in records:
        domain_counts[r["task_type"]] += 1
    print("\nInstances per domain:")
    for d, c in sorted(domain_counts.items()):
        print(f"  {d:<30} {c}")

    task_arr  = np.array([r["task_type"] for r in records])
    y_success = np.array([r["success"]   for r in records], dtype=np.int64)
    y_nsteps  = np.array([r["n_steps"]   for r in records], dtype=np.float32)
    y_complex = np.array([r["complexity"] for r in records], dtype=np.int64)

    # ── Surface features ───────────────────────────────────────────────────
    # Invalidate derived caches whenever episodes were freshly generated
    sf_path = DATA_DIR / "X_surf.npy"
    fm_path_local = DATA_DIR / "X_fm.npy"
    if need_regen:
        for _p in [sf_path, fm_path_local]:
            if _p.exists():
                _p.unlink()
    elif fm_need_regen and fm_path_local.exists():
        fm_path_local.unlink()
        print("  Deleted stale FM cache")

    def _cache_ok(path, n):
        try:
            return path.exists() and not args.force and int(np.load(path).shape[0]) == n
        except Exception:
            return False

    if _cache_ok(sf_path, len(records)):
        print(f"\nLoading existing surface features")
        X_surf = np.load(sf_path)
    else:
        print("\nComputing PDDL structural surface features (30-dim)...")
        X_surf = compute_surface_features(records)
        np.save(sf_path, X_surf)
        print(f"  Saved -> {sf_path}  shape={X_surf.shape}")

    # Verify: within-domain surface variation
    print("\nWithin-domain surface feature std (should be > 0):")
    for d in list(set(task_arr))[:3]:
        mask = (task_arr == d)
        wstd = X_surf[mask].std(axis=0).mean()
        print(f"  {d:<30} std={wstd:.4f}")

    # ── FM embeddings ──────────────────────────────────────────────────────
    fm_path = fm_path_local

    if _cache_ok(fm_path, len(records)) and not fm_need_regen:
        print(f"\nLoading existing FM embeddings ({manifest.get('fm_type','?')})")
        X_fm = np.load(fm_path)
    elif args.skip_fm:
        print("\nGenerating random FM embeddings (--skip_fm)")
        rng2 = np.random.default_rng(0)
        X_fm = rng2.normal(0, 1, (len(records), 768)).astype(np.float32)
        X_fm /= np.linalg.norm(X_fm, axis=1, keepdims=True)
        np.save(fm_path, X_fm)
    else:
        print("\nComputing FM embeddings...")
        X_fm = compute_fm_embeddings(records,
                                     model_name=args.fm_model,
                                     use_llm=args.use_llm)
        np.save(fm_path, X_fm)
        print(f"  Saved → {fm_path}  shape={X_fm.shape}")
    _write_manifest(domains, len(records), n_per_level, want_fm_type)
    print(f"  Manifest updated: domains={sorted(domains)}, fm={want_fm_type}")

    # Verify FM variation within domain
    print("\nWithin-domain FM cosine similarity (should be < 0.95 for variation):")
    for d in list(set(task_arr))[:3]:
        mask = (task_arr == d)
        Xe   = X_fm[mask]
        cos  = float((Xe @ Xe.T).mean())
        print(f"  {d:<30} cos={cos:.4f}")

    # ── Save labels and task array ─────────────────────────────────────────
    np.save(DATA_DIR / "y_success.npy",  y_success)
    np.save(DATA_DIR / "y_nsteps.npy",   y_nsteps)
    np.save(DATA_DIR / "y_complex.npy",  y_complex)
    np.save(DATA_DIR / "task_types.npy", task_arr)

    # ── Meta splits (by domain, not instance) ─────────────────────────────
    unique_domains = list(np.unique(task_arr))
    test_domains_  = [d for d in TEST_DOMAINS  if d in unique_domains]
    val_domains_   = [d for d in VAL_DOMAINS   if d in unique_domains]
    train_domains_ = [d for d in unique_domains
                      if d not in test_domains_ and d not in val_domains_]

    def get_idx(doms):
        ts = set(doms)
        return [i for i, t in enumerate(task_arr) if t in ts]

    splits = {
        "meta_train": {"tasks": train_domains_, "indices": get_idx(train_domains_)},
        "meta_val":   {"tasks": val_domains_,   "indices": get_idx(val_domains_)},
        "meta_test":  {"tasks": test_domains_,  "indices": get_idx(test_domains_)},
    }

    registry = {
        "n_total":              len(records),
        "n_domains":            len(unique_domains),
        "surf_dim":             int(X_surf.shape[1]),
        "fm_dim":               int(X_fm.shape[1]),
        "fm_model":             args.fm_model if not args.skip_fm else "random",
        "use_llm_embeddings":   args.use_llm,
        "n_complexity_levels":  5,
        "domains":              unique_domains,
        "test_domains":         test_domains_,
        "val_domains":          val_domains_,
        "train_domains":        train_domains_,
        "splits": {k: {"tasks":       v["tasks"],
                       "n_instances": len(v["indices"])}
                   for k, v in splits.items()},
    }

    (DATA_DIR / "registry.json").write_text(json.dumps(registry, indent=2))
    for name, data in splits.items():
        np.save(DATA_DIR / f"idx_{name}.npy", np.array(data["indices"]))

    print(f"\nMeta-splits (by domain):")
    for name, data in splits.items():
        print(f"  {name:<12}: {len(data['tasks'])} domains, "
              f"{len(data['indices'])} instances")
        print(f"    Domains: {data['tasks']}")

    print(f"\nAll data saved to {DATA_DIR}/")
    print("Next: python plan_step2_rplm_baseline.py")


if __name__ == "__main__":
    main()