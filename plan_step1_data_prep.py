def gen_blocksworld_problem(n_blocks, rng, domain="blocksworld"):
    """Generate a random Blocksworld problem and solve it."""
    blocks = [f"b{i}" for i in range(1, n_blocks + 1)]

    # Random initial configuration: some stacks, rest on table
    perm   = list(rng.permutation(blocks))
    init   = {"ontable": set(), "on": set(), "clear": set(), "handempty": True}
    placed = []
    for b in perm:
        if placed and rng.random() < 0.4:
            base = rng.choice(placed)
            init["on"].add((b, base))
            init["clear"].discard(base)
        else:
            init["ontable"].add(b)
        init["clear"].add(b)
        placed.append(b)

    # Random goal: 1–3 on-predicates
    n_goals = min(max(1, n_blocks // 2), 3)
    goal_pairs = set()
    while len(goal_pairs) < n_goals:
        a, b = rng.choice(blocks, 2, replace=False)
        goal_pairs.add((a, b))

    # Build PDDL strings
    if domain == "mystery_blocksworld":
        pred_map = {"on": "stacked", "ontable": "grounded",
                    "clear": "apex", "handempty": "grasping"}
        act_map  = {"pick-up": "grasp", "put-down": "release",
                    "stack": "place", "unstack": "lift"}
    else:
        pred_map = {"on": "on", "ontable": "ontable",
                    "clear": "clear", "handempty": "handempty"}
        act_map  = {}

    on_p  = pred_map["on"]
    ot_p  = pred_map["ontable"]
    cl_p  = pred_map["clear"]
    he_p  = pred_map["handempty"]

    init_facts = []
    for b in init["ontable"]:  init_facts.append(f"({ot_p} {b})")
    for (a, b) in init["on"]:  init_facts.append(f"({on_p} {a} {b})")
    for b in init["clear"]:    init_facts.append(f"({cl_p} {b})")
    init_facts.append(f"({he_p})")

    goal_facts = [f"({on_p} {a} {b})" for a, b in goal_pairs]

    problem_pddl = f"""
(define (problem bw-n{n_blocks})
  (:domain {domain})
  (:objects {' '.join(blocks)})
  (:init {' '.join(init_facts)})
  (:goal (and {' '.join(goal_facts)})))
"""

    # Build STRIPS actions for solver
    def mk_actions(bs):
        acts = []
        for x in bs:
            acts.append({"name": f"(pick-up {x})",
                         "pre": {f"({cl_p} {x})", f"({ot_p} {x})", f"({he_p})"},
                         "add": {f"(holding {x})"} if domain == "blocksworld" else {f"(clutching {x})"},
                         "del": {f"({ot_p} {x})", f"({cl_p} {x})", f"({he_p})"}})
            acts.append({"name": f"(put-down {x})",
                         "pre": {f"(holding {x})"} if domain == "blocksworld" else {f"(clutching {x})"},
                         "add": {f"({ot_p} {x})", f"({cl_p} {x})", f"({he_p})"},
                         "del": {f"(holding {x})"} if domain == "blocksworld" else {f"(clutching {x})"}})
            for y in bs:
                if x == y: continue
                acts.append({"name": f"(stack {x} {y})",
                             "pre": ({f"(holding {x})"} if domain=="blocksworld" else {f"(clutching {x})"}) | {f"({cl_p} {y})"},
                             "add": {f"({on_p} {x} {y})", f"({cl_p} {x})", f"({he_p})"},
                             "del": ({f"(holding {x})"} if domain=="blocksworld" else {f"(clutching {x})"}) | {f"({cl_p} {y})"}})
                acts.append({"name": f"(unstack {x} {y})",
                             "pre": {f"({on_p} {x} {y})", f"({cl_p} {x})", f"({he_p})"},
                             "add": ({f"(holding {x})"} if domain=="blocksworld" else {f"(clutching {x})"}) | {f"({cl_p} {y})"},
                             "del": {f"({on_p} {x} {y})", f"({cl_p} {x})", f"({he_p})"}})
        return acts

    init_set  = set(init_facts)
    goal_set  = set(goal_facts)
    actions   = mk_actions(blocks)

    plan, n_steps = bfs_plan(init_set, goal_set, actions, max_steps=10)
    valid = plan is not None

    # Richer description: encodes per-instance difficulty for FM embedding
    stacks_needed = len(goal_pairs)
    unsatisfied = sum(1 for (a,b) in goal_pairs if f"(on {a} {b})" not in init_set)
    description = (
        f"Blocksworld with {n_blocks} blocks. "
        f"Need to build {stacks_needed} stack(s): {', '.join(f'{a} on {b}' for a,b in goal_pairs)}. "
        f"{unsatisfied} of {stacks_needed} goal(s) unsatisfied in initial state. "
        f"Current arrangement: {', '.join(str(f) for f in init_facts if 'on ' in f or 'ontable' in f)[:120]}. "
        f"Estimated {'easy' if n_steps <= 3 else 'medium' if n_steps <= 7 else 'hard'} "
        f"({n_steps if valid else '>10'} steps)."
    )

    return {
        "domain":       domain,
        "n_objects":    n_blocks,
        "problem_pddl": problem_pddl.strip(),
        "domain_pddl":  DOMAIN_PDDL[domain].strip(),
        "plan":         plan or [],
        "n_steps":      n_steps if valid else int(rng.integers(12, 25)),
        "valid":        valid,
        "description":  description,
        "goal_facts":   goal_facts,
        "init_facts":   init_facts,
    }


def gen_gripper_problem(n_balls, rng):
    """Generate a Gripper problem (move balls between rooms)."""
    n_rooms    = max(2, n_balls // 2)
    rooms      = [f"room{i}" for i in range(1, n_rooms + 1)]
    balls      = [f"ball{i}" for i in range(1, n_balls + 1)]
    grippers   = ["left", "right"]

    init_room  = rooms[0]
    ball_locs  = {b: rng.choice(rooms) for b in balls}
    goal_room  = rooms[-1]
    goal_balls = list(rng.choice(balls, min(n_balls, 3), replace=False))

    init_facts = ([f"(room {r})" for r in rooms] +
                  [f"(ball {b})" for b in balls] +
                  [f"(gripper {g})" for g in grippers] +
                  [f"(at-robby {init_room})"] +
                  [f"(at {b} {ball_locs[b]})" for b in balls] +
                  [f"(free {g})" for g in grippers])

    goal_facts = [f"(at {b} {goal_room})" for b in goal_balls]

    problem_pddl = f"""
(define (problem gripper-n{n_balls})
  (:domain gripper)
  (:objects {' '.join(rooms)} {' '.join(balls)} {' '.join(grippers)})
  (:init {' '.join(init_facts)})
  (:goal (and {' '.join(goal_facts)})))
"""

    # Simple heuristic plan: move to ball location, pick, move to goal, drop
    plan = []
    current_room = init_room
    gripper_state = {"left": None, "right": None}

    def move_to(dest):
        nonlocal current_room
        if current_room != dest:
            plan.append(f"(move {current_room} {dest})")
            current_room = dest

    for b in goal_balls:
        src = ball_locs[b]
        g   = "left" if gripper_state["left"] is None else "right"
        if gripper_state[g] is not None:
            move_to(goal_room)
            plan.append(f"(drop {gripper_state[g]} {goal_room} {g})")
            gripper_state[g] = None
        move_to(src)
        plan.append(f"(pick {b} {src} {g})")
        gripper_state[g] = b

    for g, b in gripper_state.items():
        if b is not None and b in goal_balls:
            move_to(goal_room)
            plan.append(f"(drop {b} {goal_room} {g})")

    n_steps = len(plan)
    valid   = n_steps > 0

    balls_to_move = sum(1 for b in goal_balls if ball_locs[b] != goal_room)
    description = (
        f"Gripper: move {len(goal_balls)} ball(s) to {goal_room} using a 2-gripper robot. "
        f"Target balls: {', '.join(goal_balls)}. "
        f"{balls_to_move} ball(s) not yet in goal room. "
        f"Ball locations: {', '.join(f'{b} in {ball_locs[b]}' for b in goal_balls[:4])}. "
        f"Robot at {init_room}. {n_rooms} rooms. "
        f"Estimated {n_steps} steps, {'easy' if n_steps<=4 else 'medium' if n_steps<=10 else 'hard'}."
    )

    return {
        "domain":       "gripper",
        "n_objects":    n_balls + n_rooms,
        "problem_pddl": problem_pddl.strip(),
        "domain_pddl":  DOMAIN_PDDL["gripper"].strip(),
        "plan":         plan,
        "n_steps":      n_steps,
        "valid":        valid,
        "description":  description,
        "goal_facts":   goal_facts,
        "init_facts":   init_facts,
    }


def gen_ferry_problem(n_cars, rng):
    """Generate a Ferry problem (transport cars across water)."""
    n_locs   = max(2, n_cars // 2)
    locs     = [f"loc{i}" for i in range(1, n_locs + 1)]
    cars     = [f"car{i}" for i in range(1, n_cars + 1)]
    car_locs = {c: rng.choice(locs) for c in cars}
    goals    = {c: rng.choice([l for l in locs if l != car_locs[c]] or locs)
                for c in cars}

    init_facts = ([f"(location {l})" for l in locs] +
                  [f"(car {c})" for c in cars] +
                  [f"(at-ferry {locs[0]})"] +
                  [f"(at {c} {car_locs[c]})" for c in cars] +
                  ["(empty-ferry)"])

    goal_facts = [f"(at {c} {goals[c]})" for c in cars]

    problem_pddl = f"""
(define (problem ferry-n{n_cars})
  (:domain ferry)
  (:objects {' '.join(locs)} {' '.join(cars)})
  (:init {' '.join(init_facts)})
  (:goal (and {' '.join(goal_facts)})))
"""

    n_steps = n_cars * 3  # approx: sail + board + debark per car
    valid   = True

    cars_misplaced = sum(1 for c in cars
                          if f"(at {c} {goals[c]})" not in set(init_facts))
    description = (
        f"Ferry: transport {n_cars} car(s) to goal docks using a single-capacity ferry. "
        f"Cars to move: {', '.join(f'{c}->{goal_locs[c]}' for c in cars[:4])}. "
        f"{cars_misplaced}/{n_cars} cars not at goal. "
        f"{n_locs} docking locations. Ferry at {locs[0]}. "
        f"Approx {n_steps} steps (sail+board+debark per car). "
        f"{'Easy' if n_steps<=6 else 'Medium' if n_steps<=12 else 'Hard'} difficulty."
    )

    return {
        "domain":       "ferry",
        "n_objects":    n_cars + n_locs,
        "problem_pddl": problem_pddl.strip(),
        "domain_pddl":  DOMAIN_PDDL["ferry"].strip(),
        "plan":         [],
        "n_steps":      n_steps,
        "valid":        valid,
        "description":  description,
        "goal_facts":   goal_facts,
        "init_facts":   init_facts,
    }


def gen_logistics_problem(n_packages, rng):
    """Generate a Logistics problem (trucks + airplanes)."""
    n_cities = max(2, n_packages // 2)
    cities   = [f"city{i}" for i in range(1, n_cities + 1)]
    airports = [f"airport{i}" for i in range(1, n_cities + 1)]
    locs     = []
    for i, c in enumerate(cities):
        locs += [f"loc{i}_{j}" for j in range(1, 3)]
    trucks    = [f"truck{i}" for i in range(1, n_cities + 1)]
    airplanes = [f"plane1"]
    packages  = [f"pkg{i}" for i in range(1, n_packages + 1)]

    all_locs  = locs + airports
    pkg_locs  = {p: rng.choice(all_locs) for p in packages}
    pkg_goals = {p: rng.choice(all_locs) for p in packages}
    truck_locs = {t: airports[i] for i, t in enumerate(trucks)}

    init_facts = (
        [f"(in-city {airports[i]} {cities[i]})" for i in range(len(cities))] +
        [f"(in-city loc{i}_{j} {cities[i]})" for i in range(len(cities)) for j in [1,2]] +
        [f"(at {t} {truck_locs[t]})" for t in trucks] +
        [f"(at {a} {airports[0]})" for a in airplanes] +
        [f"(at {p} {pkg_locs[p]})" for p in packages]
    )
    goal_facts = [f"(at {p} {pkg_goals[p]})" for p in packages
                  if pkg_locs[p] != pkg_goals[p]]
    if not goal_facts:
        goal_facts = [f"(at {packages[0]} {airports[-1]})"]

    problem_pddl = f"""
(define (problem log-n{n_packages})
  (:domain logistics)
  (:objects {' '.join(trucks)} - truck
            {' '.join(airplanes)} - airplane
            {' '.join(airports)} - airport
            {' '.join(locs)} - location
            {' '.join(cities)} - city
            {' '.join(packages)} - package)
  (:init {' '.join(init_facts)})
  (:goal (and {' '.join(goal_facts)})))
"""

    # Estimate solvability + solution length
    # Count packages needing inter-city transfer (airplane required)
    inter_city = sum(1 for p in packages
                     if pkg_locs[p] != pkg_goals[p]
                     and pkg_locs[p].split("_")[0] != pkg_goals[p].split("_")[0])
    same_loc = sum(1 for p in packages if pkg_locs[p] == pkg_goals[p])
    n_steps = (n_packages - same_loc) * 4 + inter_city * 3
    n_steps = max(1, n_steps)
    valid   = True  # logistics always solvable; difficulty comes from n_steps variance

    pkg_summary = ', '.join(f'{p}:{pkg_locs[p]}->{pkg_goals[p]}' for p in packages[:4])
    description = (
        f"Logistics: deliver {n_packages} pkg(s) across {n_cities} cities. "
        f"Package routes: {pkg_summary}. "
        f"{inter_city} need airplane inter-city transfer; {same_loc} already at goal. "
        f"{n_packages - same_loc} deliveries needed, {n_steps} estimated steps. "
        f"{'Easy' if n_steps<=8 else 'Medium' if n_steps<=16 else 'Hard'} difficulty."
    )

    return {
        "domain":       "logistics",
        "n_objects":    n_packages + n_cities * 3,
        "problem_pddl": problem_pddl.strip(),
        "domain_pddl":  DOMAIN_PDDL["logistics"].strip(),
        "plan":         [],
        "n_steps":      n_steps,
        "valid":        valid,
        "description":  description,
        "goal_facts":   goal_facts,
        "init_facts":   init_facts,
    }


def gen_satellite_problem(n_sats, rng):
    """Generate a Satellite observation problem."""
    n_dir  = max(3, n_sats * 2)
    sats   = [f"sat{i}" for i in range(1, n_sats + 1)]
    dirs   = [f"dir{i}" for i in range(1, n_dir + 1)]
    instr  = [f"inst{i}" for i in range(1, n_sats * 2 + 1)]
    modes  = ["mode0", "mode1"]

    calib  = {ins: rng.choice(dirs) for ins in instr}
    goals  = [(rng.choice(dirs), rng.choice(modes))
               for _ in range(min(n_sats, 3))]

    init_facts = (
        [f"(satellite {s})" for s in sats] +
        [f"(direction {d})" for d in dirs] +
        [f"(instrument {i})" for i in instr] +
        [f"(mode {m})" for m in modes] +
        [f"(on_board {instr[i]} {sats[i//2]})" for i in range(len(instr))] +
        [f"(supports {ins} {rng.choice(modes)})" for ins in instr] +
        [f"(power_avail {s})" for s in sats] +
        [f"(pointing {s} {rng.choice(dirs)})" for s in sats] +
        [f"(calibration_target {ins} {calib[ins]})" for ins in instr]
    )
    goal_facts = [f"(have_image {d} {m})" for d, m in goals]

    problem_pddl = f"""
(define (problem sat-n{n_sats})
  (:domain satellite)
  (:objects {' '.join(sats)} {' '.join(dirs)} {' '.join(instr)} {' '.join(modes)})
  (:init {' '.join(init_facts)})
  (:goal (and {' '.join(goal_facts)})))
"""

    n_steps = n_sats * 5 + len(goals) * 2
    goals_str = ', '.join(f'{d}:{m}' for d,m in goals[:3])
    description = (
        f"Satellite scheduling: {n_sats} satellite(s) must image {len(goals)} direction(s). "
        f"Imaging targets: {goals_str}. "
        f"Each requires: power-on, point, calibrate, take-image ({n_sats} sats, {n_dir} dirs). "
        f"Estimated {n_steps} steps. {'Simple' if n_sats==1 else 'Multi-sat coordination'} required."
    )

    return {
        "domain":       "satellite",
        "n_objects":    n_sats + n_dir,
        "problem_pddl": problem_pddl.strip(),
        "domain_pddl":  DOMAIN_PDDL["satellite"].strip(),
        "plan":         [],
        "n_steps":      n_steps,
        "valid":        True,
        "description":  description,
        "goal_facts":   goal_facts,
        "init_facts":   init_facts,
    }


def gen_rovers_problem(n_rovers, rng):
    """Generate a Rovers planetary exploration problem."""
    n_wp   = max(4, n_rovers * 3)
    rovers = [f"rover{i}" for i in range(1, n_rovers + 1)]
    wps    = [f"wp{i}" for i in range(1, n_wp + 1)]
    stores = [f"store{i}" for i in range(1, n_rovers + 1)]
    cams   = [f"cam{i}" for i in range(1, n_rovers + 1)]
    modes  = ["colour", "high_res"]
    objs   = [f"obj{i}" for i in range(1, max(3, n_rovers) + 1)]

    lander_wp  = wps[0]
    rover_wps  = {r: rng.choice(wps) for r in rovers}
    traversals = set()
    for wp in wps:
        targets = rng.choice(wps, min(2, n_wp), replace=False)
        for t in targets:
            if t != wp:
                traversals.add((wp, t))

    # Goals: soil/rock analysis + images
    soil_goals = [rng.choice(wps) for _ in range(min(2, n_wp))]
    img_goals  = [(rng.choice(objs), rng.choice(modes))
                   for _ in range(min(n_rovers, 2))]

    init_facts = (
        [f"(rover {r})" for r in rovers] +
        [f"(waypoint {w})" for w in wps] +
        [f"(store {s})" for s in stores] +
        [f"(camera {c})" for c in cams] +
        [f"(mode {m})" for m in modes] +
        [f"(objective {o})" for o in objs] +
        [f"(at {r} {rover_wps[r]})" for r in rovers] +
        [f"(at_lander {lander_wp})"] +
        [f"(can_traverse {r} {a} {b})" for r in rovers
         for a, b in list(traversals)[:n_wp]] +
        [f"(equipped_for_soil_analysis {r})" for r in rovers] +
        [f"(equipped_for_imaging {r})" for r in rovers] +
        [f"(empty {stores[i]})" for i in range(len(rovers))] +
        [f"(on_board {cams[i]} {rovers[i]})" for i in range(len(rovers))] +
        [f"(supports {cams[i]} {rng.choice(modes)})" for i in range(len(cams))] +
        [f"(calibrated {cams[i]} {rovers[i]})" for i in range(len(cams))] +
        [f"(visible {a} {lander_wp})" for a, _ in traversals if lander_wp != a] +
        [f"(channel_free {r})" for r in rovers]
    )

    goal_facts = (
        [f"(communicated_soil_data {w})" for w in soil_goals] +
        [f"(communicated_image_data {o} {m})" for o, m in img_goals]
    )

    problem_pddl = f"""
(define (problem rov-n{n_rovers})
  (:domain rovers)
  (:objects {' '.join(rovers)} {' '.join(wps)} {' '.join(stores)}
            {' '.join(cams)} {' '.join(modes)} {' '.join(objs)})
  (:init {' '.join(init_facts)})
  (:goal (and {' '.join(goal_facts)})))
"""

    n_steps = n_rovers * 6 + len(soil_goals) * 3 + len(img_goals) * 4
    soil_str = ', '.join(soil_goals[:3])
    img_str  = ', '.join(f'{o}/{m}' for o,m in img_goals[:2])
    description = (
        f"Rovers: {n_rovers} rover(s) on {n_wp} waypoints must complete science tasks. "
        f"Soil analysis at: {soil_str}. "
        f"Images needed: {img_str}. "
        f"Rovers at: {', '.join(f'{r}@{rover_wps[r]}' for r in rovers[:3])}. "
        f"{len(traversals)} traversable edges. "
        f"~{n_steps} steps. {'Simple' if n_rovers==1 else 'Multi-rover'} coordination."
    )

    return {
        "domain":       "rovers",
        "n_objects":    n_rovers + n_wp,
        "problem_pddl": problem_pddl.strip(),
        "domain_pddl":  DOMAIN_PDDL["rovers"].strip(),
        "plan":         [],
        "n_steps":      n_steps,
        "valid":        True,
        "description":  description,
        "goal_facts":   goal_facts,
        "init_facts":   init_facts,
    }


