# ── Built-in forward-chaining STRIPS solver ───────────────────────────────────

class STRIPSState:
    """Lightweight STRIPS state for forward-chaining search."""
    def __init__(self, facts):
        self.facts = frozenset(facts)

    def satisfies(self, conditions):
        return all(c in self.facts for c in conditions)

    def apply(self, add_list, del_list):
        return STRIPSState((self.facts - set(del_list)) | set(add_list))

    def __hash__(self):  return hash(self.facts)
    def __eq__(self, o): return self.facts == o.facts


def bfs_plan(initial_facts, goal_facts, actions, max_steps=12):
    """
    BFS planner with hard node-expansion limit to keep generation fast.
    Returns (plan, n_steps) or (None, -1) if unsolvable within budget.
    max_steps kept small (12) so BFS terminates quickly on CPU.
    """
    from collections import deque
    MAX_NODES = 5000   # hard cap: abort if BFS expands more than this many states

    start = STRIPSState(initial_facts)
    goal  = frozenset(goal_facts)

    if goal.issubset(start.facts):
        return [], 0

    queue    = deque([(start, [])])
    visited  = {start}
    expanded = 0

    while queue:
        state, plan = queue.popleft()
        expanded += 1
        if expanded > MAX_NODES:
            return None, -1   # budget exhausted — treat as unsolvable
        if len(plan) >= max_steps:
            continue
        for action in actions:
            if state.satisfies(action["pre"]):
                new_state = state.apply(action["add"], action["del"])
                if new_state in visited:
                    continue
                new_plan = plan + [action["name"]]
                if goal.issubset(new_state.facts):
                    return new_plan, len(new_plan)
                visited.add(new_state)
                queue.append((new_state, new_plan))

    return None, -1


